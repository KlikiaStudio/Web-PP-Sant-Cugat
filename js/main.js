function handleContactSubmit(e){
  e.preventDefault();
  const captcha = e.target.querySelector('[name="captcha"]');
  if(captcha && captcha.value.trim() !== '5'){
    alert(I18N[currentLang].contact_captcha_error);
    captcha.focus();
    return false;
  }
  alert(currentLang==='ca'
    ? 'Formulari encara no connectat a cap servei. Consulta el checklist d\'activació per connectar-lo (Formspree, Google Forms, Mailchimp...).'
    : 'El formulario todavía no está conectado a ningún servicio. Consulta el checklist de activación para conectarlo (Formspree, Google Forms, Mailchimp...).');
  return false;
}

